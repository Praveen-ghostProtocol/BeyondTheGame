-- Supabase project-owned, private schema. No direct anonymous/client access.
CREATE SCHEMA IF NOT EXISTS btg;
CREATE EXTENSION IF NOT EXISTS citext WITH SCHEMA extensions;
CREATE TABLE btg.meta (key TEXT PRIMARY KEY, value TEXT NOT NULL);
CREATE TABLE btg.users (
 id TEXT PRIMARY KEY, username extensions.citext NOT NULL UNIQUE,
 password TEXT NOT NULL, role TEXT NOT NULL CHECK(role IN
 ('admin','secretary','student','captain','checker','guard','maintenance','office')),
 active SMALLINT NOT NULL DEFAULT 1 CHECK(active IN (0,1)), created_at TEXT NOT NULL
);
CREATE TABLE btg.sessions (
 token_hash TEXT PRIMARY KEY, user_id TEXT NOT NULL REFERENCES btg.users(id),
 csrf TEXT NOT NULL, expires DOUBLE PRECISION NOT NULL
);
CREATE INDEX sessions_user ON btg.sessions(user_id);
CREATE INDEX sessions_expiry ON btg.sessions(expires);
CREATE TABLE btg.login_attempts (key TEXT PRIMARY KEY, failures INTEGER NOT NULL, until DOUBLE PRECISION NOT NULL);
CREATE TABLE btg.records (
 kind TEXT NOT NULL, id TEXT NOT NULL, data TEXT NOT NULL CHECK(jsonb_typeof(data::jsonb)='object'),
 version INTEGER NOT NULL DEFAULT 1, updated_at TEXT NOT NULL, PRIMARY KEY(kind,id)
);
CREATE INDEX records_kind_updated ON btg.records(kind,updated_at DESC);
CREATE TABLE btg.events (
 seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, at TEXT NOT NULL,
 actor TEXT NOT NULL, role TEXT NOT NULL, action TEXT NOT NULL, target TEXT NOT NULL,
 detail TEXT NOT NULL CHECK(jsonb_typeof(detail::jsonb)='object'), provenance TEXT NOT NULL
);
CREATE INDEX events_actor_seq ON btg.events(actor,seq DESC);
CREATE FUNCTION btg.prevent_history_change() RETURNS trigger LANGUAGE plpgsql
SET search_path = pg_catalog AS $$
BEGIN RAISE EXCEPTION 'History is append-only'; END;
$$;
REVOKE ALL ON FUNCTION btg.prevent_history_change() FROM PUBLIC;
CREATE TRIGGER events_no_update BEFORE UPDATE OR DELETE ON btg.events
 FOR EACH ROW EXECUTE FUNCTION btg.prevent_history_change();
CREATE TABLE btg.operations (
 actor TEXT NOT NULL, key TEXT NOT NULL, fingerprint TEXT NOT NULL,
 result TEXT NOT NULL, PRIMARY KEY(actor,key)
);
